import api from "./api";


const authService = {

  // ==========================================================
  // REGISTER
  // ==========================================================

  register(data) {
    return api.post(
      "/auth/register",
      data
    );
  },


  // ==========================================================
  // LOGIN
  // ==========================================================

  login(data) {
    return api.post(
      "/auth/login",
      data
    );
  },


  // ==========================================================
  // REFRESH SESSION
  // ==========================================================

  refresh() {
    return api.post(
      "/auth/refresh"
    );
  },


  // ==========================================================
  // CURRENT USER
  // ==========================================================

  getCurrentUser() {
    return api.get(
      "/users/me"
    );
  },


  // ==========================================================
  // LOGOUT
  // ==========================================================

  logout() {
    return api.post(
      "/auth/logout"
    );
  },

};


export default authService;